// Renames functions from a map (address, VB6 object, name) using one namespace per object,
// and exports the decompiled code to one .c file per object.
// Args: <map.tsv> <output_dir>
import ghidra.app.script.GhidraScript;
import ghidra.app.decompiler.*;
import ghidra.program.model.listing.Function;
import ghidra.program.model.symbol.*;
import java.io.*;
import java.nio.file.*;
import java.util.*;

public class ExportSource extends GhidraScript {
    @Override
    public void run() throws Exception {
        String[] a = getScriptArgs();
        File out = new File(a[1]);
        out.mkdirs();
        SymbolTable st = currentProgram.getSymbolTable();
        Map<String, List<Function>> byObject = new TreeMap<>();
        Set<String> used = new HashSet<>();
        for (String l : Files.readAllLines(Paths.get(a[0]))) {
            String[] p = l.split("\t");
            Function f = getFunctionAt(toAddr(p[0]));
            if (f == null) continue;
            String obj = p[1].replace("+", "__");
            Namespace ns = st.getNamespace(obj, currentProgram.getGlobalNamespace());
            if (ns == null) ns = st.createNameSpace(currentProgram.getGlobalNamespace(), obj, SourceType.ANALYSIS);
            String name = p[2], n = name;
            for (int k = 2; used.contains(obj + "::" + n); k++) n = name + "_" + k;
            used.add(obj + "::" + n);
            f.setParentNamespace(ns);
            for (int k = 2; ; k++) {  // another function may still hold this name from an older map
                try { f.setName(n, SourceType.ANALYSIS); break; }
                catch (ghidra.util.exception.DuplicateNameException ex) { n = p[2] + "_" + k; }
            }
            byObject.computeIfAbsent(obj, x -> new ArrayList<>()).add(f);
        }
        DecompInterface di = new DecompInterface();
        di.setOptions(new DecompileOptions());
        di.openProgram(currentProgram);
        for (Map.Entry<String, List<Function>> e : byObject.entrySet()) {
            try (PrintWriter w = new PrintWriter(new File(out, e.getKey() + ".c"), "UTF-8")) {
                w.println("// " + currentProgram.getName() + " :: " + e.getKey().replace("__", " + "));
                w.println("// C pseudocode generated by Ghidra from native VB6 code. Not the original source.");
                w.println("// Functions: " + e.getValue().size());
                w.println();
                for (Function f : e.getValue()) {
                    monitor.checkCancelled();
                    DecompileResults r = di.decompileFunction(f, 180, monitor);
                    w.println("// ---- " + f.getName() + " @ " + f.getEntryPoint());
                    if (r.decompileCompleted()) w.println(r.getDecompiledFunction().getC());
                    else w.println("// decompilation failed: " + r.getErrorMessage() + "\n");
                }
            }
        }
        println("Exported " + byObject.size() + " objects from " + currentProgram.getName());
    }
}
